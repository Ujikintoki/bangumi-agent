def expand_aliases(query: str) -> list[str]:
    """从用户 query 中识别已知社群缩写，返回对应的正式名称列表。

    匹配逻辑: 全小写子串匹配。
    因为只收录无歧义缩写，子串匹配不会误触发。

    Args:
        query: 用户原始查询，如 ``"邦邦第三季好看吗"``

    Returns:
        匹配到的正式名称列表，如 ``["BanG Dream!"]``
    """
    if not query:
        return []
    q_lower = query.lower()
    expanded: list[str] = []
    for alias, formal_names in ANIME_ALIASES.items():
        if alias in q_lower:
            expanded.extend(formal_names)
    return expanded
